use std::fs::{self, OpenOptions};
use std::io::{ErrorKind, Write};
use std::path::Path;

use anyhow::Context;
use sha2::{Digest, Sha256};

use crate::errtemplate;

/// Name of the salt file at the store root. A dotfile sibling of `store/`,
/// deliberately outside the shareable capture tree — see `doctor` and
/// `README.md` / `docs/install.md` for the sharing boundary this depends on.
pub const SALT_FILENAME: &str = ".salt";

/// Per-install secret used to salt error fingerprints. Generated once and
/// persisted at `<root>/.salt` — a dotfile sibling of `store/`, deliberately
/// outside the shareable capture tree; never leaves the machine and never
/// appears in stored output. See `README.md` and `docs/install.md` for the
/// sharing boundary this depends on.
pub struct Salt([u8; 32]);

impl Salt {
    /// Loads the salt from `<root>/.salt`, creating it (mode 0600 on Unix)
    /// from two random UUIDs if it does not yet exist. If another process
    /// wins a concurrent first-run creation race, re-reads the file it wrote
    /// rather than returning this process's own generated (and discarded)
    /// value — see `create`.
    pub fn load(root: &Path) -> anyhow::Result<Self> {
        let path = root.join(SALT_FILENAME);
        match fs::read(&path) {
            Ok(bytes) => Self::from_file_bytes(&path, bytes),
            Err(error) if error.kind() == ErrorKind::NotFound => Self::create(&path),
            Err(error) => Err(error).with_context(|| format!("reading {}", path.display())),
        }
    }

    /// A fixed salt for tests. Never used outside the test suite.
    pub fn for_tests() -> Self {
        Self([0u8; 32])
    }

    pub fn from_bytes(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }

    fn bytes(&self) -> &[u8; 32] {
        &self.0
    }

    fn from_file_bytes(path: &Path, bytes: Vec<u8>) -> anyhow::Result<Self> {
        let bytes: [u8; 32] = bytes.try_into().map_err(|bytes: Vec<u8>| {
            anyhow::anyhow!(
                "salt file at {} has {} bytes, expected 32",
                path.display(),
                bytes.len()
            )
        })?;
        Ok(Self(bytes))
    }

    /// Creates the salt file so that two processes racing on first run
    /// cannot both "win" and silently disagree about which salt is on disk,
    /// and so that no racer ever reads back a half-written file.
    ///
    /// Writes the generated bytes to a uniquely-named temporary file first
    /// (mode 0600 on Unix), fully and durably, then hard-links it onto
    /// `path`. `hard_link` fails with `AlreadyExists` rather than
    /// overwriting when `path` already exists, so exactly one racer's link
    /// succeeds; every other racer's `AlreadyExists` means some racer's
    /// *fully written* file is already there — a plain create+truncate
    /// would let a reader observe `path` after creation but before its
    /// content is written. Losers discard their own generated bytes and
    /// read back what is actually on disk, so every process — winner or
    /// loser — ends up returning the one salt that is persisted.
    fn create(path: &Path) -> anyhow::Result<Self> {
        let salt = Self::generate();
        let tmp_name = format!(
            "{}.tmp-{}",
            path.file_name()
                .and_then(|name| name.to_str())
                .unwrap_or(SALT_FILENAME),
            uuid::Uuid::new_v4()
        );
        let tmp_path = path.with_file_name(tmp_name);

        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        {
            let mut file = options
                .open(&tmp_path)
                .with_context(|| format!("creating {}", tmp_path.display()))?;
            file.write_all(&salt.0)
                .with_context(|| format!("writing {}", tmp_path.display()))?;
            file.sync_all()
                .with_context(|| format!("syncing {}", tmp_path.display()))?;
        }

        let link_result = fs::hard_link(&tmp_path, path);
        let _ = fs::remove_file(&tmp_path);

        match link_result {
            Ok(()) => Ok(salt),
            Err(error) if error.kind() == ErrorKind::AlreadyExists => {
                let bytes =
                    fs::read(path).with_context(|| format!("reading {}", path.display()))?;
                Self::from_file_bytes(path, bytes)
            }
            Err(error) => Err(error)
                .with_context(|| format!("linking {} to {}", tmp_path.display(), path.display())),
        }
    }

    fn generate() -> Self {
        let mut bytes = [0u8; 32];
        bytes[..16].copy_from_slice(uuid::Uuid::new_v4().as_bytes());
        bytes[16..].copy_from_slice(uuid::Uuid::new_v4().as_bytes());
        Self(bytes)
    }
}

/// Lowercase hex fingerprint of the first 8 bytes of
/// `SHA256(salt || 0x00 || skeleton(message))`. Non-invertible: the message
/// never appears in the result, and a different salt yields a different
/// fingerprint for the same message.
pub fn template_id(salt: &Salt, message: &str) -> String {
    let skeleton = errtemplate::skeleton(message);
    let mut hasher = Sha256::new();
    hasher.update(salt.bytes());
    hasher.update([0u8]);
    hasher.update(skeleton.as_bytes());
    let digest = hasher.finalize();
    let mut id = String::with_capacity(16);
    for byte in &digest[..8] {
        id.push_str(&format!("{byte:02x}"));
    }
    id
}
